#include <string>
#include <vector>

void gcd_triple() {
    int a = 24, b = 36, c = 60;
    int g = a;
    for (int d = g; d >= 1; --d) {
        if (a % d == 0 && b % d == 0 && c % d == 0) { g = d; break; }
    }
    (void)g;
}

void is_prime() {
    int n = 97;
    bool prime = (n > 1);
    for (int d = 2; d * d <= n; ++d) {
        if (n % d == 0) { prime = false; break; }
    }
    (void)prime;
}

void count_spaces() {
    std::string text = "a b  c   d";
    int spaces = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        if (text[i] == ' ') spaces += 1;
    }
    (void)spaces;
}

void count_down() {
    int acc = 0;
    for (int i = 8; i > 0; --i) acc += i;
    (void)acc;
}

extern "C" int cobalt_bridge();
extern "C" void lucid_compass();
extern "C" void eager_thicket();
extern "C" void prime_kite();

int main() {
    gcd_triple();
    is_prime();
    count_spaces();
    count_down();
    lucid_compass();
    eager_thicket();
    prime_kite();
    return cobalt_bridge();
}
